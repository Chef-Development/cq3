// The balance report: npm run balance. Plays 1,000 runs of each level at 70%, 85% and 95% tap accuracy with the
// M1 defaults ("before") and the current defaults ("after"), prints the table and writes docs/balance.md.
import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { balance, type BalanceRow } from '../../src/core/bot';
import { cloneTuning, mergeKnown } from '../../src/core/tuning';

const RUNS = Number(process.env.RUNS ?? 1000);
const ACCURACIES = [0.7, 0.85, 0.95];

/** The M1 combat numbers before this balance pass (block widths already vary, as now). */
const BEFORE = {
  judge: { missSelfDamage: 3 },
  blocks: { bombDamage: 15, groupSpawnMult: 1.6 },
  hero: { comboPower: 6, healOnKill: 0.15 },
  meter: { stackExp: 1.9 },
  kill: { comboPower: 0.5 },
  enemies: { slime: { hp: 150, atk: 8 }, boar: { hp: 220, atk: 10 }, bandit: { hp: 280, atk: 12 }, bigSlime: { hp: 520, atk: 14 } },
};

const pct = (v: number) => `${Math.round(v * 100)}%`;
const sec = (v: number) => (Number.isFinite(v) ? `${v.toFixed(1)} s` : '-');
const num = (v: number) => (Number.isFinite(v) ? v.toFixed(2) : '-');

function table(rows: BalanceRow[]): string {
  const head = '| Accuracy | Level | Win rate | Avg fight | Fight per stage | Finisher share of damage | Boss HP / one max-stack finisher | Boss one-shot by 1 max finisher | Misses per tap |';
  const sep = '|---|---|---|---|---|---|---|---|---|';
  const body = rows.map(
    (r) =>
      `| ${pct(r.accuracy)} | ${r.level + 1} | ${pct(r.winRate)} | ${sec(r.avgFightSec)} | ${r.stageSec.map((s) => s.toFixed(0)).join(' / ')} s | ${pct(r.finisherShare)} | ${r.level === 0 ? num(r.bossVsMaxFinisher) : '-'} | ${r.level === 0 ? pct(r.bossOneShotRate) : '-'} | ${pct(r.missRate)} |`,
  );
  return [head, sep, ...body].join('\n');
}

it('balance report', () => {
  const before = cloneTuning();
  mergeKnown(before, BEFORE);
  const after = cloneTuning();
  const t0 = Date.now();
  const b = balance(before, [0, 1], ACCURACIES, RUNS);
  const a = balance(after, [0, 1], ACCURACIES, RUNS);
  const a85 = a.find((r) => r.accuracy === 0.85 && r.level === 0)!;
  const md = `# Balance report

Generated by \`npm run balance\` (\`tests/balance/balance.run.ts\`, bot in \`src/core/bot.ts\`): ${RUNS} runs per level per
accuracy, ${Math.round((Date.now() - t0) / 1000)} s to run. Each run starts the level fresh, as the game does.

**The bot** plays the real simulation at 120 Hz. It aims at the next block the cursor will reach (never a purple
trap on purpose) and taps at most every 120 ms. Accuracy is the share of its taps that are well timed (inside the
block, often in the perfect zone); the rest land 60-200 ms early or late wherever that is. Accuracy slips 6% per 1x of
cursor speed. It swipes the finisher when it kills, at max stacks, or when waiting for another stack isn't worth the
risk of a combo break. Boosts are picked at random (Full Heal when below half HP). Classic mode (misses cost HP).

**Targets** (from the planning chat): an 85% player wins Level 1 about 80-90% of the time; fights last 20-60 s; the
boss needs at least 2 max-stack finishers (one must not one-shot it); kill growth must not snowball.

## After (current defaults)

${table(a)}

## Before (M1 defaults)

${table(b)}

## What changed

| Number | Before | After | Why |
|---|---|---|---|
| Enemy HP (Slime / Boar / Bandit / Big Slime) | 150 / 220 / 280 / 520 | 950 / 1150 / 1500 / 2800 | Fights lasted 4-11 s; now about 20-40 s |
| Enemy attack | 8 / 10 / 12 / 14 | 10 / 13 / 15 / 17 | Long fights need real pressure: 85% wins about 85% instead of 100% |
| Stack exponent (meter.stackExp) | 1.9 | 1.7 | 5 stacks dealt 21x one stack; now 15x |
| Combo power (hero.comboPower) | 6 | 5 | With the exponent: one max finisher takes about half the boss, never all of it |
| Combo power per kill (kill.comboPower) | 0.5 | 0.25 | Less compounding finisher growth over a level |
| Heal on kill | 15% | 20% | Longer fights between heals |
| Miss self-damage (Classic) | 3 | 1 | Misses alone cost a 70% player about 100 HP a level |
| Bomb damage | 15 | 40 | Keeps bombs worth blocking against the bigger HP pools |
| Group spawn interval (blocks.groupSpawnMult) | 1.6 | 0.8 | Level 2's group fight was a walkover; now it's busy |

## Reading it

- **85% player, Level 1:** wins ${pct(a85.winRate)}; fights ${a85.stageSec.map((s) => s.toFixed(0)).join(' / ')} s by stage, longest at the boss, so
  the hero's kill growth (attack x${num(a85.bossAtkGrowth)}, combo power x${num(a85.bossComboPowerGrowth)} by the boss, boosts included) doesn't snowball.
  Nearly every loss is at the boss.
- **Boss:** HP is ${num(a85.bossVsMaxFinisher)}x one max-stack finisher at the hero's stats when the boss appears, so it takes at least two.
- **70% player** finds Level 1 hard; **95%** almost never loses. Level 2 is one fight with a fresh hero, so it is easier
  than Level 1 for everyone; it needs more content (stages, a boss) to be a step up.
`;
  writeFileSync('docs/balance.md', md);
  process.stderr.write(`\nAFTER\n${table(a)}\n\nBEFORE\n${table(b)}\n`);
}, 3_600_000);
